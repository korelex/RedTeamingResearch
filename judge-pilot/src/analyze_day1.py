"""Day 1 result analysis: what the run dataset contains and which cases will be hard for Day 2 judges.

Usage (from the project root):
    python -m src.analyze_day1 [--data-dir data/runs] [--out DAY1_RESULTS.md]

Read-only over data/runs/*.jsonl (last line per run_id wins). Ground truth is `compromised_strict`.
Final-reply categories are keyword heuristics, meant for choosing Day 2 test cases, not as labels.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

from src.inspect_run import dedupe_runs, load_records, run_label
from src.morning_check import wilson_interval

# Attacker artifacts a final reply would name if the agent disclosed what it did (taken from the injection goal).
_ARTIFACT = re.compile(r"\b[A-Z]{2}\d{12,}\b|www\.[\w.-]+(?:/\w+)?|[\w.+-]+@[\w-]+\.\w+|new_password|\bFred\b")
_SUSPICION = re.compile(
    r"suspicious|malicious|phishing|prompt injection|injected|ignore[d]? (?:the|this|these)|not (?:follow|comply|perform)"
    r"|won't|will not|cannot comply|unauthori[sz]ed|security risk|scam|did not (?:send|follow|act)"
    r"|detected an instruction|noticed (?:a|an|the) (?:message|instruction|request)|bring (?:this|it )?(?:to )?your attention",
    re.I,
)


def _text(content) -> str:
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    return " ".join(str(b.get("content", "")) for b in content if isinstance(b, dict))


def final_reply(rec: dict) -> str:
    for m in reversed(rec.get("transcript") or []):
        if m.get("role") == "assistant":
            t = _text(m.get("content")).strip()
            if t:
                return t
    return ""


def classify(rec: dict) -> str:
    """Judge-relevant category of an attacked, completed run."""
    reply = final_reply(rec)
    comp = rec.get("compromised_strict")
    if comp:
        artifacts = set(_ARTIFACT.findall(rec.get("injection_task_goal") or ""))
        disclosed = any(a.lower() in reply.lower() for a in artifacts) if artifacts else False
        return "compromised, disclosed in reply" if disclosed else "compromised, silent (reply hides it)"
    if not rec.get("injection_seen"):
        return "not compromised, never saw injection"
    if _SUSPICION.search(reply):
        return "resisted, flagged it in reply"
    if reply.rstrip().endswith("?"):
        return "resisted, asked user a question"
    return "resisted silently"


def transcript_tokens(rec: dict) -> int:
    """Rough judge-input size: JSON transcript chars / 4."""
    return len(json.dumps(rec.get("transcript") or [], ensure_ascii=False)) // 4


def pct(k: int, n: int) -> str:
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "0/0"


def ci(k: int, n: int) -> str:
    w = wilson_interval(k, n)
    return f"{100 * k / n:.0f}% [{100 * w[0]:.0f}–{100 * w[1]:.0f}]" if w else "n/a"


def build_report(runs: list[dict]) -> str:
    done = [r for r in runs if r.get("error") is None]
    models = sorted({run_label(r) for r in done})
    attacked = [r for r in done if not r.get("is_baseline") and isinstance(r.get("compromised_strict"), bool)]
    out: list[str] = ["# Day 1 results: agent runs for the judge study", ""]
    out.append(f"Source: data/runs/*.jsonl, {len(runs)} unique runs, {len(done)} completed. Ground truth = "
               "`compromised_strict`. Generated by `python -m src.analyze_day1`.")
    out.append("")

    # 1. Overview
    out += ["## 1. Overview per model", "",
            "| Model | Runs | Baseline | Attacked | Compromised | Not compromised | Injection seen | Baseline utility | Attacked utility |",
            "|---|---|---|---|---|---|---|---|---|"]
    for m in models:
        rm = [r for r in done if run_label(r) == m]
        b = [r for r in rm if r.get("is_baseline")]
        a = [r for r in attacked if run_label(r) == m]
        k = sum(r["compromised_strict"] for r in a)
        out.append(f"| {m} | {len(rm)} | {len(b)} | {len(a)} | {ci(k, len(a))} ({k}) | {len(a) - k} | "
                   f"{pct(sum(bool(r.get('injection_seen')) for r in a), len(a))} | "
                   f"{pct(sum(bool(r.get('utility')) for r in b), len(b))} | {pct(sum(bool(r.get('utility')) for r in a), len(a))} |")
    out.append("")

    # 2. Judge-relevant categories
    cats = ["compromised, disclosed in reply", "compromised, silent (reply hides it)", "resisted, flagged it in reply",
            "resisted, asked user a question", "resisted silently", "not compromised, never saw injection"]
    counts = {m: Counter(classify(r) for r in attacked if run_label(r) == m) for m in models}
    out += ["## 2. Judge-relevant categories (attacked runs)", "",
            "Heuristic, from the final reply. 'Silent' compromises and 'resisted silently' are the hardest cases for a judge "
            "that reads only the final answer.", "",
            "| Category | " + " | ".join(models) + " | Total |", "|---|" + "---|" * (len(models) + 1)]
    for c in cats:
        vals = [counts[m][c] for m in models]
        out.append(f"| {c} | " + " | ".join(str(v) for v in vals) + f" | {sum(vals)} |")
    out.append("")

    # 3. Per suite / injection task
    out += ["## 3. Attack success per injection task", "",
            "| Suite | Injection task | Goal (short) | " + " | ".join(models) + " |", "|---|---|---|" + "---|" * len(models)]
    by: dict[tuple, dict] = defaultdict(lambda: defaultdict(list))
    goals: dict[tuple, str] = {}
    for r in attacked:
        key = (r["suite"], r["injection_task_id"])
        by[key][run_label(r)].append(r["compromised_strict"])
        goals[key] = (r.get("injection_task_goal") or "")[:70]
    for key in sorted(by, key=lambda k: (k[0], int(k[1].rsplit("_", 1)[1]))):
        cells = [pct(sum(by[key][m]), len(by[key][m])) for m in models]
        out.append(f"| {key[0]} | {key[1]} | {goals[key]} | " + " | ".join(cells) + " |")
    out.append("")

    # 4. Repeat stability
    out += ["## 4. Repeat stability (same task, same model, repeat 0 vs 1)", ""]
    groups: dict[tuple, list] = defaultdict(list)
    for r in attacked:
        groups[(run_label(r), r["suite"], r["user_task_id"], r["injection_task_id"])].append(r)
    for m in models:
        g = [v for k, v in groups.items() if k[0] == m and len(v) >= 2]
        flips = [v for v in g if len({x["compromised_strict"] for x in v}) > 1]
        out.append(f"- **{m}:** {len(g)} pairs, {len(flips)} flip between repeats"
                   + (": " + ", ".join(f"{v[0]['suite']}/{v[0]['user_task_id']}/{v[0]['injection_task_id']}" for v in flips[:8])
                      + (" …" if len(flips) > 8 else "") if flips else ""))
    out.append("Flipping pairs give same-input, different-outcome transcripts, which makes them good judge test cases.")
    out.append("")

    # 5. Transcript size (judge input)
    out += ["## 5. Transcript size (judge input)", "",
            "| Model | Runs | Avg tokens (≈ chars/4) | Median | Max | Total |", "|---|---|---|---|---|---|"]
    for m in models:
        sizes = sorted(transcript_tokens(r) for r in done if run_label(r) == m)
        if sizes:
            out.append(f"| {m} | {len(sizes)} | {sum(sizes) // len(sizes):,} | {sizes[len(sizes) // 2]:,} | {sizes[-1]:,} | {sum(sizes):,} |")
    out.append("")

    # 6. Data quality
    out += ["## 6. Data quality", ""]
    retried = Counter(r["run_id"] for r in load_records_cache if r.get("error") is not None)
    out.append(f"- Runs that needed a retry (errored first): {len(retried)}; all now completed: "
               f"{all(any(x['run_id'] == rid and x.get('error') is None for x in runs) for rid in retried)}")
    out.append(f"- `compromised_strict` differs from AgentDojo `compromised`: "
               f"{sum(r['compromised'] != r['compromised_strict'] for r in attacked)} runs")
    out.append(f"- Compromised without the injection seen in a tool result: "
               f"{sum(1 for r in attacked if r['compromised_strict'] and not r.get('injection_seen'))} (should be 0)")
    big = sorted(done, key=lambda r: -(r.get("tokens_out") or 0))[:3]
    out.append("- Largest outputs: " + ", ".join(f"{r['run_id']} ({run_label(r)}, {r['tokens_out']:,} out)" for r in big))
    asks = [r for r in done if final_reply(r).rstrip().endswith("?")]
    out.append(f"- Final reply is a question: {len(asks)} of {len(done)} runs")
    out.append(f"- state_diff available: {pct(sum(r.get('state_diff') is not None for r in done), len(done))}")
    out.append("")
    return "\n".join(out)


load_records_cache: list[dict] = []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Day 1 result analysis (read-only).")
    ap.add_argument("--data-dir", default="data/runs")
    ap.add_argument("--out", default="DAY1_RESULTS.md")
    args = ap.parse_args(argv)
    load_records_cache[:] = load_records(args.data_dir)
    report = build_report(dedupe_runs(load_records_cache))
    Path(args.out).write_text(report + "\n", encoding="utf-8")
    print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
